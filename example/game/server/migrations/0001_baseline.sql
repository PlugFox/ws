-- Baseline schema of the game server (PostgreSQL 18).
--
-- Applied by `sqlx::migrate!` at boot (`db::migrations`); sqlx records it in
-- `_sqlx_migrations` with its checksum, so this file never changes once it
-- has run anywhere that matters: schema changes go in a new numbered file
-- (`0002_<what>.sql`, ...), applied in order exactly once.
--
-- Conventions: BIGINT identity keys, TIMESTAMPTZ (UTC) times, JSONB for the
-- documents the server owns as a whole (bags, loadouts, stats; nothing
-- queries inside them, so there are no GIN indexes), plain indexed columns
-- for everything that is filtered or ranked. Names that must be unique
-- regardless of case (accounts, characters) have a unique index on
-- `lower(...)`, and lookups compare `lower(col) = lower($1)` to use it.

-- Accounts.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'active',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_username_lower_key ON users (lower(username));

-- Login sessions with rotating refresh tokens (`auth::refresh`): the
-- current token's hash, the previous one's (reuse detection) and the
-- generation. One live (unrevoked) session per account is the norm.
CREATE TABLE sessions (
    id                 UUID PRIMARY KEY,
    user_id            BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    device_id          TEXT,
    refresh_hash       BYTEA NOT NULL,
    refresh_generation INTEGER NOT NULL DEFAULT 0,
    prev_refresh_hash  BYTEA,
    rotated_at         TIMESTAMPTZ,
    ip_address         TEXT,
    country            TEXT,
    user_agent         TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at         TIMESTAMPTZ,
    revoked_reason     TEXT
);
-- The newest live session of an account; also the revoke-all scan.
CREATE INDEX sessions_user_live_idx ON sessions (user_id, created_at DESC) WHERE revoked_at IS NULL;

-- Characters. `inventory` holds the bag stacks (`combat::Stack`),
-- `equipment` the ten slots (`combat::Bag::equip`; NULL = never set, the
-- character gets the starting kit on load), `loadout` the learned skills
-- and hotbar (`combat::Loadout`). The lifetime counters (`world::record`)
-- are plain columns: the leaderboard ranks by them.
CREATE TABLE characters (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name             TEXT NOT NULL,
    archetype        TEXT NOT NULL,
    level            INTEGER NOT NULL DEFAULT 1,
    base_exp         BIGINT NOT NULL DEFAULT 0,
    stats            JSONB NOT NULL DEFAULT '{}',
    unlocked_skills  JSONB NOT NULL DEFAULT '[]',
    inventory        JSONB NOT NULL DEFAULT '[]',
    equipment        JSONB,
    loadout          JSONB NOT NULL DEFAULT '{}',
    weapon           TEXT NOT NULL DEFAULT '',
    zeny             BIGINT NOT NULL DEFAULT 0,
    last_location_id TEXT NOT NULL DEFAULT 'hub_central',
    gender           SMALLINT NOT NULL DEFAULT 0,
    hair_style       SMALLINT NOT NULL DEFAULT 1,
    hair_color       SMALLINT NOT NULL DEFAULT 0,
    body_color       SMALLINT NOT NULL DEFAULT 0,
    kills            BIGINT NOT NULL DEFAULT 0,
    mvp_kills        BIGINT NOT NULL DEFAULT 0,
    deaths           BIGINT NOT NULL DEFAULT 0,
    missions_cleared BIGINT NOT NULL DEFAULT 0,
    best_combo       INTEGER NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX characters_name_lower_key ON characters (lower(name));
CREATE INDEX characters_user_idx ON characters (user_id);

-- Leaderboard (`db::leaderboard_repo`): one index per board in exactly the
-- board's order (descending key, then the older character first), so a
-- page is an index walk and a rank (`(key) > ($1, ...)`) an index-only
-- range count.
CREATE INDEX characters_lb_level_idx ON characters (level DESC, base_exp DESC, id);
CREATE INDEX characters_lb_kills_idx ON characters (kills DESC, id);
CREATE INDEX characters_lb_mvp_idx ON characters (mvp_kills DESC, kills DESC, id);
CREATE INDEX characters_lb_zeny_idx ON characters (zeny DESC, id);

-- Security / account events (reserved; nothing writes them yet).
CREATE TABLE audit_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT REFERENCES users (id) ON DELETE SET NULL,
    event_type TEXT NOT NULL,
    ip_address TEXT,
    country    TEXT,
    details    JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX audit_events_user_idx ON audit_events (user_id);

-- Account-level friends (`db::friend_repo`): one row per direction;
-- state 0 = friends, 1 = `user_id` asked `friend_id` (pending).
CREATE TABLE friends (
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    friend_id  BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    state      SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, friend_id)
);
-- Requests waiting on an account (`friend_id = $1 AND state = 1`).
CREATE INDEX friends_asked_idx ON friends (friend_id, state);

-- Player feedback (`db::feedback_repo`, the Scribe / Kafra form; read and
-- closed by operators through MCP). `kind`: bug | suggestion | balance |
-- other; `priority`: low | normal | high | critical; `status`: open |
-- closed. The rest is context captured at submission.
CREATE TABLE feedback (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT REFERENCES users (id) ON DELETE SET NULL,
    character_id   BIGINT REFERENCES characters (id) ON DELETE SET NULL,
    character_name TEXT NOT NULL DEFAULT '',
    kind           TEXT NOT NULL,
    priority       TEXT NOT NULL,
    title          TEXT NOT NULL,
    body           TEXT NOT NULL,
    status         TEXT NOT NULL DEFAULT 'open',
    resolution     TEXT,
    map            TEXT NOT NULL DEFAULT '',
    pos_x          DOUBLE PRECISION,
    pos_y          DOUBLE PRECISION,
    level          INTEGER,
    class          TEXT NOT NULL DEFAULT '',
    client_version TEXT NOT NULL DEFAULT '',
    server_version TEXT NOT NULL DEFAULT '',
    user_agent     TEXT NOT NULL DEFAULT '',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at      TIMESTAMPTZ
);
-- MCP listing (`status = $1 ... ORDER BY id DESC`).
CREATE INDEX feedback_status_idx ON feedback (status, id);
-- The per-account rate limit (`user_id = $1 AND created_at > now() - 1 day`).
CREATE INDEX feedback_user_idx ON feedback (user_id, created_at);
