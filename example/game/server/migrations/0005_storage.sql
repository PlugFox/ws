-- Account storage (`session::storage`): stacks and zeny every character of
-- an account shares. Never authoritative in memory: each move locks the
-- character row, then this row, and writes both in one transaction.
-- `items` is the `inventory` column's form (`[{"id","n","a"?}]`).
CREATE TABLE account_storage (
    user_id    BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    zeny       BIGINT NOT NULL DEFAULT 0 CHECK (zeny >= 0),
    items      JSONB NOT NULL DEFAULT '[]'::jsonb,
    rev        BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Every storage move, written in the move's transaction (audits, support).
-- `dir`: 0 bag → storage, 1 storage → bag; `items`: `[[key, count], ...]`.
CREATE TABLE storage_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    character_id BIGINT NOT NULL,
    dir          SMALLINT NOT NULL,
    items        JSONB NOT NULL,
    zeny         BIGINT NOT NULL,
    at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX storage_log_user ON storage_log (user_id, at);

-- The character row's revision: every writer of a session's character
-- (the flusher, trades, storage moves) writes `rev + 1` only where `rev`
-- is still the one its memory was loaded at, so a displaced session's
-- late flush can never overwrite what a newer session stored.
ALTER TABLE characters ADD COLUMN rev BIGINT NOT NULL DEFAULT 0;
