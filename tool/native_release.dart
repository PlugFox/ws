// Regenerates lib/src/native/native_release.dart: the package version from
// pubspec.yaml and the library hashes from native/prebuilt/checksums.json
// (written by the release workflow). Run before `dart pub publish`.
//
//   dart run tool/native_release.dart [path/to/checksums.json]
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final version = RegExp(
    r'^version:\s*(\S+)',
    multiLine: true,
  ).firstMatch(File('pubspec.yaml').readAsStringSync())![1]!;
  final checksums = File(
    args.isEmpty ? 'native/prebuilt/checksums.json' : args.first,
  );
  final hashes = checksums.existsSync()
      ? (jsonDecode(checksums.readAsStringSync()) as Map<String, Object?>)
            .cast<String, String>()
      : const <String, String>{};
  final entries = (hashes.keys.toList()..sort())
      .map((k) => "  '$k':\n      '${hashes[k]}',\n")
      .join();
  File('lib/src/native/native_release.dart').writeAsStringSync('''
// Generated by `dart run tool/native_release.dart`; do not edit by hand.
// The release workflow regenerates it from native/prebuilt/checksums.json
// before publishing (DECISIONS.md D32).

/// Version of this package; `dart run ws:install` downloads the library of
/// the same release.
const String wsVersion = '$version';

/// GitHub release that holds the native libraries of this version.
const String nativeReleaseTag = wsVersion;

/// SHA-256 of each released library, by `<target>/<file name>` (the layout
/// of `native/prebuilt/`). Empty until the first release with libraries.
const Map<String, String> nativeAssetHashes = <String, String>{${entries.isEmpty ? '' : '\n$entries'}};
''');
  stdout.writeln(
    'native_release.dart: ws $version, ${hashes.length} libraries',
  );
}
